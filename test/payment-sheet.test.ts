import { describe, it, expect } from "vitest";
import { readSheetRows, planFromSheet, pairByClock, type SheetPayment } from "@/lib/payment-sheet";

/* The college's payment report is the only proof money arrived. Reading it
   wrongly either confirms a place nobody paid for or leaves a paid student
   waiting, so the rules here are deliberately dull and explicit. */

/* Shaped exactly like the real export: a preamble the university puts above
   the table, then the header, then the rows. */
const GRID: unknown[][] = [
  [],
  ["", "MS Ramaiah University of Applied Sciences"],
  ["", "Report Generated Date : 2026-09-21"],
  ["", "Generated By : Deepak Varadam"],
  ["Sr.No", "Registration Number", "Name", "Email ID", "Payment Amount / Status", "Mobile Number",
   "Number of participant :", "Transaction Date", "Transaction Number", "Category"],
  [1, "19092162", "Dhanya umesh ", "dhanyaau07@gmail.com", "200.00292", "9980255354", "1",
   "2026-09-16 12:38:16.0", "XSKR2QZ2USANLKE", "Fest "],
  [2, "19105140", "Aishwarya", "AISHWARYA@example.com ", "200.00292", "8690898364", "1",
   "2026-09-16 15:27:55.0", "6KNCOCDWEYEQK77", "Fest "],
  ["", "", "", "", "", "", "", "", "", ""],
];

const app = (over: Record<string, unknown> = {}) =>
  ({
    ticketId: "PRV-1", eventId: "chaos", eventName: "CHAOS", status: "pending", payment: "awaiting",
    fee: "Rs. 200/-", name: "Someone", email: "someone@example.com", phone: "9", college: "RUAS",
    teamName: null, teamCode: null, members: null, paymentRef: null, appliedAt: "2026-09-16T09:00:00.000Z",
    ...over,
  }) as any;

const pay = (email: string, transaction = "TXN0000000000001", paidAt = "2026-09-16 12:38:16.0"): SheetPayment => ({
  name: "N", email, transaction, amount: "200.00292", paidAt,
});

describe("readSheetRows", () => {
  it("finds the table under the university's preamble", () => {
    const rows = readSheetRows(GRID);
    expect(rows).toHaveLength(2);
    expect(rows[0]).toMatchObject({
      email: "dhanyaau07@gmail.com",
      transaction: "XSKR2QZ2USANLKE",
      name: "Dhanya umesh",
    });
  });

  it("lowercases and trims the address the report was typed with", () => {
    expect(readSheetRows(GRID)[1].email).toBe("aishwarya@example.com");
  });

  it("skips blank and total rows rather than inventing payments", () => {
    expect(readSheetRows([...GRID, ["", "", "", "TOTAL", "400"]])).toHaveLength(2);
  });

  it("answers nothing for a spreadsheet that is not this report", () => {
    expect(readSheetRows([["Some", "other", "sheet"], [1, 2, 3]])).toEqual([]);
  });
});

describe("planFromSheet", () => {
  it("approves a registration the report pays for, and carries the reference across", () => {
    const plan = planFromSheet([pay("someone@example.com", "XSKR2QZ2USANLKE")], [app()]);
    expect(plan.approve).toHaveLength(1);
    expect(plan.approve[0]).toMatchObject({ email: "someone@example.com", transaction: "XSKR2QZ2USANLKE", teamSize: 1 });
    expect(plan.unmatched).toHaveLength(0);
  });

  /* They already quoted their own reference; the sheet must not overwrite it. */
  it("leaves a reference the student already gave us alone", () => {
    const plan = planFromSheet([pay("someone@example.com")], [app({ paymentRef: "MINE1234567890" })]);
    expect(plan.approve[0].transaction).toBeNull();
  });

  it("counts the teammates who get confirmed alongside the payer", () => {
    const rows = [
      app({ email: "lead@example.com", teamCode: "TEAM1", payment: "awaiting" }),
      app({ email: "m1@example.com", teamCode: "TEAM1", payment: "not_required", ticketId: "PRV-2" }),
      app({ email: "m2@example.com", teamCode: "TEAM1", payment: "not_required", ticketId: "PRV-3" }),
    ];
    const plan = planFromSheet([pay("lead@example.com")], rows);
    expect(plan.approve).toHaveLength(1);
    expect(plan.approve[0].teamSize).toBe(3);
  });

  /* Teammates owe nothing, so they are never matched against a payment. */
  it("never treats a teammate as somebody who should have paid", () => {
    const rows = [app({ email: "m1@example.com", teamCode: "TEAM1", payment: "not_required" })];
    const plan = planFromSheet([], rows);
    expect(plan.unpaid).toHaveLength(0);
  });

  it("reports a payment with no registration behind it rather than dropping it", () => {
    const plan = planFromSheet([pay("stranger@example.com")], [app()]);
    expect(plan.approve).toHaveLength(0);
    expect(plan.unmatched.map((u) => u.email)).toEqual(["stranger@example.com"]);
  });

  it("reports registrations this sheet does not pay for", () => {
    const plan = planFromSheet([], [app({ email: "waiting@example.com" })]);
    expect(plan.unpaid).toHaveLength(1);
    expect(plan.unpaid[0].email).toBe("waiting@example.com");
  });

  /* The rule that stops one payment confirming three places — and the clock
     that decides which of the three it was. */
  it("approves only as many registrations as the person actually paid for", () => {
    const rows = [
      app({ eventId: "chaos", email: "multi@example.com", appliedAt: "2026-09-16T09:00:00.000Z" }),
      app({ eventId: "respawn", email: "multi@example.com", appliedAt: "2026-09-16T10:00:00.000Z", ticketId: "PRV-2" }),
      app({ eventId: "hammer", email: "multi@example.com", appliedAt: "2026-09-16T11:00:00.000Z", ticketId: "PRV-3" }),
    ];
    /* Registered for Respawn at 10:00 UTC = 15:30 IST; paid twenty minutes
       later, which the report writes in IST. */
    const plan = planFromSheet([pay("multi@example.com", "T1", "2026-09-16 15:50:00.0")], rows);
    expect(plan.approve).toHaveLength(1);
    expect(plan.approve[0].eventId).toBe("respawn");
    expect(plan.short).toEqual([{ email: "multi@example.com", payments: 1, inReview: 3 }]);
    expect(plan.unpaid.map((u) => u.eventId).sort()).toEqual(["chaos", "hammer"]);
  });

  it("covers two registrations when the report shows two payments", () => {
    const rows = [
      app({ eventId: "chaos", email: "multi@example.com", appliedAt: "2026-09-16T09:00:00.000Z" }),
      app({ eventId: "respawn", email: "multi@example.com", appliedAt: "2026-09-16T10:00:00.000Z", ticketId: "PRV-2" }),
    ];
    const plan = planFromSheet([pay("multi@example.com", "T1"), pay("multi@example.com", "T2")], rows);
    expect(plan.approve.map((a) => a.eventId).sort()).toEqual(["chaos", "respawn"]);
    expect(plan.short).toEqual([]);
  });

  it("does not re-approve somebody already confirmed", () => {
    const plan = planFromSheet([pay("done@example.com")], [app({ email: "done@example.com", status: "confirmed", payment: "paid" })]);
    expect(plan.approve).toHaveLength(0);
    expect(plan.alreadyConfirmed).toBe(1);
  });

  it("ignores withdrawn and declined registrations entirely", () => {
    const rows = [
      app({ email: "gone@example.com", status: "cancelled" }),
      app({ email: "no@example.com", status: "declined", ticketId: "PRV-2" }),
    ];
    const plan = planFromSheet([pay("gone@example.com"), pay("no@example.com")], rows);
    expect(plan.approve).toHaveLength(0);
    expect(plan.unmatched).toHaveLength(2);
    expect(plan.unpaid).toHaveLength(0);
  });

  it("matches however the address was capitalised in either place", () => {
    const plan = planFromSheet([pay("Mixed@Example.com".toLowerCase())], [app({ email: "MIXED@example.com" })]);
    expect(plan.approve).toHaveLength(1);
  });
});

/* The report has no event column, so with two entries and one payment the
   only evidence of which event was paid for is when the money moved. */
describe("pairByClock", () => {
  const entry = (eventId: string, appliedAt: string, ticketId: string) =>
    app({ eventId, appliedAt, ticketId, email: "multi@example.com" });

  it("gives the payment to the registration made just before it", () => {
    const rows = [
      entry("chaos", "2026-09-16T09:00:00.000Z", "PRV-1"),
      entry("respawn", "2026-09-16T14:00:00.000Z", "PRV-2"),
    ];
    /* 14:00 UTC is 19:30 IST; the report stamps the payment at 19:42 IST. */
    const pairs = pairByClock([pay("multi@example.com", "T1", "2026-09-16 19:42:00.0")], rows);
    expect(pairs).toHaveLength(1);
    expect(pairs[0].application.eventId).toBe("respawn");
  });

  it("keeps two payments in step with the two registrations they followed", () => {
    const rows = [
      entry("chaos", "2026-09-16T09:00:00.000Z", "PRV-1"),
      entry("respawn", "2026-09-16T14:00:00.000Z", "PRV-2"),
    ];
    const pairs = pairByClock(
      [
        pay("multi@example.com", "LATER", "2026-09-16 19:40:00.0"),
        pay("multi@example.com", "EARLIER", "2026-09-16 14:35:00.0"),
      ],
      rows,
    );
    expect(pairs.map((p) => [p.application.eventId, p.payment.transaction])).toEqual([
      ["chaos", "EARLIER"],
      ["respawn", "LATER"],
    ]);
  });

  /* Clocks disagree: the portal stamped the payment a minute before our own
     row. Still the same intent, read from the other side. */
  it("takes the nearest registration after the payment when none came before", () => {
    const rows = [entry("chaos", "2026-09-16T14:00:00.000Z", "PRV-1")];
    /* 19:29 IST = 13:59 UTC, a minute before our own row. */
    const pairs = pairByClock([pay("multi@example.com", "T1", "2026-09-16 19:29:00.0")], rows);
    expect(pairs[0].application.eventId).toBe("chaos");
  });

  it("falls back to registration order when the report has no usable date", () => {
    const rows = [
      entry("chaos", "2026-09-16T09:00:00.000Z", "PRV-1"),
      entry("respawn", "2026-09-16T14:00:00.000Z", "PRV-2"),
    ];
    const pairs = pairByClock([pay("multi@example.com", "T1", "")], rows);
    expect(pairs[0].application.eventId).toBe("chaos");
  });

  it("never pairs two payments with the same registration", () => {
    const rows = [entry("chaos", "2026-09-16T09:00:00.000Z", "PRV-1")];
    const pairs = pairByClock(
      [pay("multi@example.com", "A", "2026-09-16 15:00:00.0"), pay("multi@example.com", "B", "2026-09-16 16:00:00.0")],
      rows,
    );
    expect(pairs).toHaveLength(1);
  });
});
