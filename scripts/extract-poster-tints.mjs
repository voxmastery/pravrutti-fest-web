/**
 * Reads every poster in public/posters/ and writes its dominant colour to
 * lib/poster-tints.ts.
 *
 * Luma washes each event page in a colour taken from that event's cover, which
 * is why no two event pages look alike. Tinting by category instead gives eight
 * events one hue. Deriving the tint from the actual image file means the wash
 * always matches the art — including after real artwork replaces a placeholder,
 * since re-running this picks up the new file.
 *
 *   node scripts/extract-poster-tints.mjs
 */
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const postersDir = join(root, "public", "posters");

const files = readdirSync(postersDir).filter((f) => f.endsWith(".png"));
if (files.length === 0) {
  console.error("No posters found. Run generate-posters.mjs first.");
  process.exit(1);
}

const py = `
import json, sys, colorsys
from PIL import Image

paths = json.loads(sys.stdin.read())
out = {}

for slug, path in paths.items():
    im = Image.open(path).convert("RGB").resize((16, 16), Image.BILINEAR)
    best, best_score = None, -1.0
    for (r, g, b) in im.getdata():
        h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
        # Favour saturated mid-tones. A plain average of a dark poster returns
        # near-black, which produces no visible wash at all.
        if l < 0.12 or l > 0.9:
            continue
        score = s * (1.0 - abs(l - 0.5))
        if score > best_score:
            best_score, best = score, (r, g, b)
    if best is None:
        best = im.getpixel((8, 8))
    out[slug] = list(best)

print(json.dumps(out))
`;

const paths = Object.fromEntries(files.map((f) => [f.replace(/\.png$/, ""), join(postersDir, f)]));
const tints = JSON.parse(execFileSync("python3", ["-c", py], { input: JSON.stringify(paths), encoding: "utf8" }));

const body = `// GENERATED by scripts/extract-poster-tints.mjs — do not edit by hand.
// Dominant colour of each event poster, used to tint the page wash per event
// the way Luma derives its background from an event's cover art.
// Re-run the script after changing any poster.

export const POSTER_TINTS: Record<string, [number, number, number]> = {
${Object.entries(tints)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([slug, rgb]) => `  "${slug}": [${rgb.join(", ")}],`)
  .join("\n")}
};
`;

writeFileSync(join(root, "lib", "poster-tints.ts"), body);
console.log(`Extracted ${Object.keys(tints).length} tints -> lib/poster-tints.ts`);
const sample = Object.entries(tints).slice(0, 3);
for (const [s, rgb] of sample) console.log(`  ${s}: rgb(${rgb.join(",")})`);
